import mongoose from 'mongoose'

const otpCodeSchema = new mongoose.Schema(
  {
    email: {
      type: String,
      required: true,
      lowercase: true,
      trim: true,
      index: true,
    },
    phone: {
      type: String,
      required: true,
      trim: true,
    },
    name: {
      type: String,
      required: true,
      trim: true,
    },
    otpHash: {
      type: String,
      required: true,
    },
    expiresAt: {
      type: Date,
      required: true,
      index: true,
    },
    used: {
      type: Boolean,
      default: false,
    },
  },
  { timestamps: true }
)

otpCodeSchema.index({ expiresAt: 1 }, { expireAfterSeconds: 0 })

export default mongoose.model('OtpCode', otpCodeSchema)